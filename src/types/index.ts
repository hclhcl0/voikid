export type StickerTier = 'basic' | 'star' | 'rare' | 'legendary' | 'special';

export interface Sticker {
  id: string;
  name: string;         // e.g. "Mèo Học Giỏi"
  emoji: string;        // e.g. "🐱"
  tier: StickerTier;
  setId: string;        // themed set grouping
  unitId?: string;      // which unit it belongs to
  gradeId?: string;     // which grade level
  condition: string;    // human-readable description of how to earn
  earnedAt: string;     // ISO date when earned
}

export interface Badge {
  id: string;
  name: string;
  description: string;
  emoji: string;
  earnedAt: string;
}

export type UnitTestGrade = 'excellent' | 'good' | 'pass' | 'fail';

export interface UnitTestResult {
  correctAnswers?: number;
  questionCount?: number;
  unitId: string;
  score: number;           // 0–130
  grade: UnitTestGrade;
  completedAt: string;
  attempts: number;
  fastAnswers: number;     // answers within < 3s
  streak: number;          // best streak in the attempt
}

export interface AppProgress {
  progressResetAt?: string;
  stickerStudyDays?: string[];
  ipaPractice?: Record<string, import('@/lib/ipa/practice').IpaPracticeRecord>;
  storySessions?: Record<string, import('@/lib/stories/types').StorySession>;
  deletedStories?: Record<string,string>;
  learningSessions?: Record<string, import('@/lib/learning/types').LearningSession>;
  learningRewardKeys?: string[];
  totalStars: number;
  streak: number;
  lastActiveDate: string;
  wordProgress: Record<string, WordProgress>;
  dailyStats: DailyStats[];

  // ── Gamification (v2) ──
  stickers: Sticker[];
  badges: Badge[];
  unitTestResults: Record<string, UnitTestResult>;  // key = unitId
  unlockedUnits: string[];                           // manually unlocked by admin
  totalPoints: number;                               // cumulative score
}
